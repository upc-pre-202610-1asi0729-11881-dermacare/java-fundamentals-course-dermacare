public class Lesson04_ControlFlow {
    public static void main(String[] args) {
        int nota = 14;
        if (nota >= 18) System.out.println("Excelente");
        else if (nota >= 11) System.out.println("Aprobado");
        else System.out.println("Desaprobado");
        for (int i = 1; i <= 10; i++) System.out.println("Número: " + i);
    }
}
